def get_personas_by_category() -> Dict[str, List[Dict]]:
    """按6大分类获取演练角色。

    Returns:
        {category_id: [personas...]}
    """
    result = {}
    for p in ROLEPLAY_PERSONAS:
        cat = p.get('category', 'other')
        if cat not in result:
            result[cat] = []
        result[cat].append(p)
    return result


def get_persona(persona_id: str) -> Optional[Dict]:
    """按ID获取角色。"""
    for p in ROLEPLAY_PERSONAS:
        if p['id'] == persona_id:
            return p
    return None


def evaluate_roleplay(history: List[Dict], persona: Dict, llm=None) -> str:
    """根据演练对话历史生成复盘评价(优先使用LLM深度分析+点评用户回复)。

    Args:
        history: 对话历史 [{'role','content'}]
        persona: 角色信息
        llm: 可选的LLM客户端,用于生成深度复盘

    Returns:
        复盘评价文本。
    """
    user_messages = [h['content'] for h in history if h['role'] == 'user']
    real_user_msgs = [m for m in user_messages if '(请开始你的开场白)' not in m]

    # 用户没有实际回复
    if len(real_user_msgs) == 0:
        return (
            '📋 **模拟演练复盘**\n\n'
            '⚠️ **你还没有与骗子对话就结束了演练。**\n\n'
            '建议:重新开始演练,像真实场景一样回应骗子的话术。\n'
            '只有实际体验过诈骗话术的压迫感,才能真正建立防骗肌肉记忆!\n\n'
            f'🎯 **本角色关键防骗要点:** {persona["success_criteria"]}'
        )

    # 用户回复太少(只有1条)
    if len(real_user_msgs) == 1:
        return (
            '📋 **模拟演练复盘**\n\n'
            f'💬 **你只回复了 1 条消息就结束了演练,体验还不够充分。**\n\n'
            f'你的回复:「{real_user_msgs[0][:80]}」\n\n'
            '建议:多与骗子对话几轮,体验完整的话术升级过程(恐吓→施压→诱导转账),\n'
            '这样复盘才能发现你在哪个环节容易动摇。\n\n'
            f'🎯 **本角色关键防骗要点:** {persona["success_criteria"]}\n\n'
            '💡 **心理战术分析:** 骗子利用的核心心理:恐惧(公检法)、贪婪(刷单/投资)、'
            '孤独(杀猪盘)、慌张(客服退款)。破解方法:慢下来→核实→拒绝→求助。'
        )

    # ===== 有足够对话,使用LLM深度分析 =====
    # 构建对话记录(排除system和占位消息)
    transcript_lines = []
    turn = 0
    for h in history:
        if h['role'] == 'system':
            continue
        if h['role'] == 'user' and '(请开始你的开场白)' in h['content']:
            continue
        if h['role'] == 'user':
            turn += 1
            transcript_lines.append(f'[用户第{turn}轮] {h["content"]}')
        elif h['role'] == 'assistant':
            transcript_lines.append(f'[骗子] {h["content"]}')
    transcript = '\n'.join(transcript_lines)

    # 如果没有LLM,回退到简单分析
    if llm is None:
        return _fallback_evaluation(real_user_msgs, persona)

    # 构建复盘prompt
    review_prompt = f"""你是一位资深反诈教育专家,正在对学生的模拟演练进行复盘。

【演练角色】{persona['name']} - {persona['desc']}
【防骗要点】{persona['success_criteria']}
【常见陷阱】{'、'.join(persona['trap_points'])}

【完整对话记录】
{transcript}

请生成一份详细复盘报告。核心要求:

1. **逐条点评用户的每一条回复**——这是最重要的部分!对用户每一轮回复:
   - 指出做得好的地方(如果有)
   - **重点指出不妥当、不正确、有风险的地方**(比如:只是骂"骗子"但没有挂断/报警;态度模糊没有明确拒绝;被骗子的话术带着走;询问转账细节说明已被引导等)
   - 如果用户只是说"你是骗子"但没有采取正确行动(挂断、报警、核实),必须指出"光识破还不够,正确做法是XX"
   - 如果用户的回复有动摇、犹豫、被引导的迹象,必须点出来

2. **总结用户踩了哪些陷阱**(对照常见陷阱逐条检查)

3. **总结用户做对了什么**(只有真正做对的才算,不要虚假表扬)

4. **给出具体改进建议**(针对用户暴露出的弱点)

5. 语气:客观严格但鼓励,不虚假表扬,也不打击信心

输出格式(严格遵循):

📋 **模拟演练复盘**

💬 **逐条点评:**
(对用户每一轮回复进行点评,格式:第X轮:「用户原话缩略」→ ✅做得好的/⚠️问题的)

⚠️ **踩到的陷阱:**
(列出,没有则写"无明显陷阱")

✅ **做对了的:**
(列出,没有则写"暂无突出表现")

🎯 **改进建议:**
(针对弱点给出具体建议)

💡 **本角色防骗要点:** {persona['success_criteria']}"""

    try:
        messages = [
            {"role": "system", "content": "你是反诈教育专家,擅长分析学生在模拟演练中的表现并给出专业复盘。"},
            {"role": "user", "content": review_prompt},
        ]
        review = llm.chat(messages)
        return review
    except Exception:
        # LLM失败,回退到简单分析
        return _fallback_evaluation(real_user_msgs, persona)


def _fallback_evaluation(real_user_msgs: List[str], persona: Dict) -> str:
    """LLM不可用时的简单复盘(关键词版,但更严格)。"""
    lines = ['📋 **模拟演练复盘**', '']
    lines.append(f'💬 **对话轮数:** 你回复了 {len(real_user_msgs)} 条消息')
    lines.append('')

    # 严格检查:用户是否真正采取了正确行动(不只是嘴上说)
    correct_actions = []
    risky_behaviors = []

    joined = ' '.join(real_user_msgs)

    # 正确行动(必须伴随实际行动)
    if any(w in joined for w in ['挂断', '挂了', '挂电话']):
        correct_actions.append('选择了挂断电话(正确!)')
    if any(w in joined for w in ['报警', '110', '96110']):
        correct_actions.append('选择报警(正确!)')
    if any(w in joined for w in ['我自己查', '自己核实', '打官方', '去派出所', '去银行问']):
        correct_actions.append('选择自己通过官方渠道核实(正确!)')
    if any(w in joined for w in ['不转', '不给', '拒绝']):
        correct_actions.append('明确拒绝了对方要求')

    # 风险行为
    if any(w in joined for w in ['怎么转', '转多少', '转哪里', '卡号是', '验证码']):
        risky_behaviors.append('询问了转账细节或提供了敏感信息(已被引导!)')
    if any(w in joined for w in ['好的', '行', '可以', '嗯']):
        if not any(w in joined for w in ['不', '别', '拒', '挂']):
            risky_behaviors.append('回复中有顺从/模糊表态(应明确拒绝)')

    # 只说"骗子"但没行动
    said_scammer_only = any(w in joined for w in ['骗子', '假的', '骗人']) and len(correct_actions) == 0
    if said_scammer_only:
        risky_behaviors.append('只是识破了骗子但没有采取正确行动(应挂断+报警+核实)')

    if risky_behaviors:
        lines.append('⚠️ **需要注意的问题:**')
        for r in risky_behaviors:
            lines.append(f'  • ❌ {r}')
        lines.append('')
    else:
        lines.append('✅ **没有出现明显的风险行为。**')
        lines.append('')

    if correct_actions:
        lines.append('🛡️ **你做对了这些:**')
        for c in correct_actions:
            lines.append(f'  • {c}')
        lines.append('')
    elif not risky_behaviors:
        lines.append('💡 你的回复比较中性。面对骗子应该**明确拒绝+挂断+报警**,而不是保持模糊态度。')
        lines.append('')

    lines.append(f'🎯 **本角色关键防骗要点:** {persona["success_criteria"]}')
    lines.append('')
    lines.append('💡 **心理战术分析:** 骗子利用的核心心理:恐惧(公检法)、贪婪(刷单/投资)、'
                 '孤独(杀猪盘)、慌张(客服退款)。破解方法:慢下来→核实→拒绝→求助。')

    return '\n'.join(lines)